// The depth we can honestly claim: the largest m such that EVERY allowed size from the type's smallest
// up to it has a finished search record (coverage.js contiguousTo). A deep run that skipped sizes does
// not raise it.
function depthOf(r) { const s = storeOf(r.i); return s && s.c != null ? s.c : null; }

// Two different questions, so two different sentences (John, 2026-09-25):
//   possible -> a tile is already known; the search was for an ANISOHEDRAL tiling
//   unknown  -> the search was for ANY tile at all
//   impossible -> no line at all
function findsOf(r) {
  // The store only holds irreducible finds (judge.js never judges a reducible combo).
  const s = storeOf(r.i);
  return s ? [...new Set(s.a.map(c => c[0]))].sort((a, b) => a - b) : [];
}

// Your own searches, if this browser has any for this type. Always a separate sentence from the published
// one, and always said to be yours: it is real work, but it is not in the record until the file is imported.
function mineLine(r) {
  const m = mineOf(r.i); if (!m) return '';
  const nf = (m.finds || []).filter(f => f.kind === 'anisohedral').length;
  return `<div class="why mine"><b>Your searches</b> in this browser: m = ${m.sizes.join(', ')}`
    + (nf ? `, with <b>${nf}</b> anisohedral find${nf === 1 ? '' : 's'}` : ', nothing found')
    + `. <span class="muted">Not in the published record — use File &rsaquo; Save your searches and send the file.</span></div>`;
}
function searchLine(r) {
  if (r.v === 'X') return '';
  const d = depthOf(r);
  const finds = findsOf(r);
  if (r.v === 'P') {
    if (d == null) return `<div class="why muted">No anisohedral search on record.</div>` + mineLine(r);
    return `<div class="why">` + (finds.length
      ? `Anisohedral tilings found at m = ${finds.join(', ')}.`
      : `No anisohedral tiling found, searched to m = ${d}.`) + `</div>` + mineLine(r);
  }
  // unknown
  if (d == null) return `<div class="why muted">No search on record for this type.</div>` + mineLine(r);
  let t = `No tile of any kind found, searched to m = ${d}.`;
  if (finds.length) t += ` Anisohedral tilings found at m = ${finds.join(', ')}.`;
  return (t ? `<div class="why">${t}</div>` : '') + mineLine(r);
}

// ---------- drawing one tile ------------------------------------------------------------------
// A turtle walk over (interior angles, edge lengths) reproduces the engine's TC.verticesOf
// EXACTLY (checked: max vertex error 0.00e+0), so no solver has to be ported here.
function tileVerts(A, L) {
  const v = [[0, 0]]; let x = 0, y = 0, dir = 0;
  for (let i = 0; i < L.length; i++) {
    x += L[i] * Math.cos(dir); y += L[i] * Math.sin(dir); v.push([x, y]);
    dir += Math.PI - A[(i + 1) % A.length] * Math.PI / 180;
  }
  return v.slice(0, L.length);
}

// One curve per edge ORBIT, so edges that must match are drawn identically -- that is what makes
// the picture readable. Stored curves win: those 29 tiles are only tiles BECAUSE of the curve.
// Everything else gets a standard motif, chosen by orbit, purely as decoration.
function curveSet(m, we, es, stored) {
  if (!window.TilerCurves) return null;
  const TCv = window.TilerCurves, byOrbit = {}, out = [];
  for (let i = 0; i < m; i++) {
    const orb = we ? we[i] : 0, symCode = es ? es[i] : 0;
    if (byOrbit[orb] === undefined) {
      let c = null;
      if (stored) {                                   // a stored curve for any edge of this orbit
        for (let j = 0; j < m; j++) if ((we ? we[j] : 0) === orb && stored[j]) {
          try { c = TCv.buildCanon(stored[j].type, stored[j].pts); } catch (e) { c = null; }
          break;
        }
      }
      if (!c) {                                       // standard motif for this orbit
        const t = TCv.SYM ? (TCv.SYM[symCode] || 'I') : 'I';
        try {
          const n = TCv.motifCount ? TCv.motifCount(t) : 0;
          c = n ? TCv.buildCanon(t, TCv.motifPts(t, orb % n)) : [[0, 0], [1, 0]];
        } catch (e) { c = [[0, 0], [1, 0]]; }
      }
      byOrbit[orb] = c;
    }
    out.push(byOrbit[orb]);
  }
  return out;
}

// SVG for one tile: curved boundary if we can build one, straight otherwise.
function tileSvg(c, px, curves) {
  const [m, si, or, off, flags, A, L, stored, we, es] = c;
  if (!A || !L) return '';
  const base = tileVerts(A, L);
  let pts = base;
  if (curves) {
    const cs = curveSet(m, we, es, stored);
    if (cs && window.TilerCurves.curvedTile) {
      try { pts = window.TilerCurves.curvedTile(base, cs); } catch (e) { pts = base; }
    }
  }
  let minx = Infinity, miny = Infinity, maxx = -Infinity, maxy = -Infinity;
  for (const p of pts) { minx = Math.min(minx, p[0]); miny = Math.min(miny, p[1]);
                         maxx = Math.max(maxx, p[0]); maxy = Math.max(maxy, p[1]); }
  const w = maxx - minx, h = maxy - miny, sc = (px - 8) / Math.max(w, h, 1e-9);
  const X = p => (8 + (p[0] - minx) * sc).toFixed(2);
  const Y = p => (px - 8 - (p[1] - miny) * sc).toFixed(2);   // y up
  const d = pts.map((p, i) => (i ? 'L' : 'M') + X(p) + ' ' + Y(p)).join(' ') + ' Z';
  const needsCurves = !!(flags & 16);
  return `<svg viewBox="0 0 ${px} ${px}" width="${px}" height="${px}">`
    + `<path d="${d}" fill="${needsCurves ? '#3a2f4a' : '#2b3340'}" stroke="var(--accent)" stroke-width="1.4"/></svg>`;
}

