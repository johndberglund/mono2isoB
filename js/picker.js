function comboBlock(r) {
  // The list is the STORE's, one row per combo. The picture for each comes from data/aniso_shapes.js, which
  // program7/export_aniso_shapes.js generates FROM the store -- so a find can never be newer than its picture
  // (John, 2026-10-05: #2425's finds were a night old and the old combos.js cache had no shape for them).
  // Drawing goes through window.Render, the same code the card's tile uses: it walks whichEdge to each edge's
  // orbit representative and applies the Klein mapping code, which is what makes the curves line up.
  const st = storeOf(r.i);
  if (!st || !(st.a.length || (st.s && st.s.length))) return '';
  // first green card pulls the shapes in, then redraws itself with the pictures
  if (shapesState !== 'ready' && shapesState !== 'failed') loadShapes(() => { if (state.selectedId === r.i) renderCard(r); });
  const SH = window.ANISO_SHAPES || {};
  // `s` = combos of tiles that are isohedral only by splitting an I side. They are isohedral, so they are not listed as
  // anisohedral -- except for an m where nothing else is listed, which they are the only combo of (John, 2026-10-17).
  const aM = new Set(st.a.map(f => f[0]));
  const rows = st.a.map(f => [f, false]).concat((st.s || []).filter(f => !aM.has(f[0])).map(f => [f, true]));
  const list = rows.map(([f, iso]) => ({ m: f[0], si: f[1], or: f[2], off: f[3], block: f[4], crit: f[5], prov: f[6], vers: f[7] || [], iso,
                                shape: SH[r.i + '/' + f[0] + '/' + f[1] + '/' + f[2] + '/' + f[3]] || null }));
  const d = depthOf(r);
  const row = c => `<tr><td>${c.m}</td><td>${c.si}</td><td>${c.or}</td><td>${c.off}</td>`
    + `<td>${c.block ? c.block + ' tile' + (c.block === 1 ? '' : 's') : ''}</td>`
    + `<td>${(c.crit || []).join(', ')}</td>`
    + `<td class="muted">${c.prov === 'search' ? (c.vers.length ? 'v' + c.vers.join(', v') : '') : c.prov}</td></tr>`;
  const head = `<tr><th>m</th><th>si</th><th>refl</th><th>off</th><th>block</th><th>criteria</th><th>found by</th></tr>`;
  let h = `<h3>${list.every(c => c.iso) ? 'isohedral' : 'anisohedral'} combos (${list.length})</h3>`
    + `<div class="muted" style="font-size:12px;margin-bottom:6px">`
    + (d != null ? `searched to m = ${d}` : 'depth not established') + `</div>`;
  const drawable = list.filter(c => c.shape);
  lastDrawn = drawable;
  if (drawable.length) {
    h += `<div class="minigal">` + drawable.map((c, i) => {
      const svg = window.Render ? window.Render.tileSvg(c.shape, 96, { curves: true, fill: c.iso ? ISO_FILL : ANISO_FILL }) : '';
      return `<figure class="gtile opens" data-open="aniso" data-i="${i}"`
        + ` title="open in Explore on this shape — m=${c.m} si=${c.si} refl=${c.or} off=${c.off}`
        + `">${svg || '<div class="nodraw">no shape</div>'}`
        + `<figcaption>m${c.m}</figcaption></figure>`;
    }).join('') + `</div>`;
  }
  // Reducible combos are deliberately not drawn: they describe the same physical tile with a redundant
  // vertex, so the gallery drops them and export_aniso_shapes.js no longer spends time on them
  // (John, 2026-10-13). Saying "no picture yet — run the exporter" about those would be a false alarm.
  if (drawable.length < list.length) {
    const RED = window.ANISO_REDUCIBLE || {};
    const undrawn = list.filter(c => !c.shape);
    const red = undrawn.filter(c => RED[r.i + '/' + c.m + '/' + c.si + '/' + c.or + '/' + c.off]).length;
    const rest = undrawn.length - red;
    const bits = [];
    if (red) bits.push(`${red} reducible — the same tile with a redundant vertex, so not drawn`);
    if (rest) bits.push(`${rest} with no picture yet — run program7/export_aniso_shapes.js`);
    h += `<div class="muted" style="font-size:12px">${bits.join('; ')}</div>`;
  }
  h += `<table class="combos">${head}${list.map(row).join('')}</table>`;
  return h;
}

// ---------- the info card ----------
function renderCard(r) {
  const card = $('card');
  if (!r) { card.innerHTML = '<div class="placeholder">Pick a type — by sides, orbifold, picture, or a Tegula id.</div>'; return; }

  let meta = `<div class="meta"><b>${sigOf(r)}</b> · orbifold <b>${r.o}</b>`;
  if (r.d) meta += ` · vertex degrees <b>${r.d}</b>`;
  if (r.pl) meta += ` · paper ${r.pl}${r.pn != null ? ` (fig. ${r.pn})` : ''}`;
  meta += '</div>';

  let body = '';
  if (r.v === 'X') {
    const why = r.pt || (r.pr >= 0 && REASONS[r.pr]) || '';   // r.pt: the reason of a proof accepted from the proof builder
    body = `<span class="chip X">impossible</span>` +
      `<div class="why"><b>#${r.i}</b> admits no tiling at all${r.pg ? ` (${r.pg})` : ''}.` +
      (why ? ` ${why}` : '') + `</div>` +
      (r.pf ? `<div class="proof"><img src="proofs/${r.pf}" alt="proof for #${r.i}"></div>` : '');
  } else if (r.v === 'P') {
    // Green only when an anisohedral example is known -- the same test as the grid tick. A possible
    // type with only isohedral combos gets the yellow chip: it tiles, but the interesting question
    // is still open, and a green chip there claimed more than we know.
    const aniso = hasAniso(r.i);
    // A yellow type gets the counterpart of an impossible type's proof picture: one isohedral combo
    // at the LOWEST m, drawn as a single tile -- the image showing it does tile. Absent for the 16
    // yellow types where no isohedral example is recorded; no placeholder, since "we have not stored
    // one" and "there is none" are different things.
    body = `<span class="chip ${aniso ? 'A' : 'P'}">possible</span>` + (aniso ? '' : isoEgHtml(r.i)) +
      `<div class="why"><b>#${r.i}</b> is known to tile` +
      (aniso ? `, and an <b>anisohedral</b> example is known.` :
               `. Only <b>isohedral</b> combos found so far.`) + `</div>` + searchLine(r);
  } else {
    body = `<span class="chip U">unknown</span>` +
      `<div class="why"><b>#${r.i}</b> is undecided.</div>` + searchLine(r);
  }

  if (!r.t) {
    body += `<div class="note">No net data for this type — the perimeter argument settles it ` +
      `without ever constructing a tile, so there is nothing to draw here yet.</div>`;
  }

  if (r.v !== 'X') body += comboBlock(r);
  // first card render pulls combos.js in; when it lands, redraw so the depth and list appear
  if (combosState === 'idle') loadCombos(() => {
    refreshFilterViews();                        // marks: yellow tick may become green
    if (state.selectedId === r.i) renderCard(r);
  });

  // Explore is offered for every type that HAS net data -- including impossible ones, where seeing WHY
  // each combo fails is the interesting part.
  const explore = r.t ? `<div class="exOpen"><button id="openExplore">Explore this type &rarr;</button>
    <span class="muted">pick m, sum-type, orientation and offset</span></div>` : '';
  card.innerHTML =
    `<img class="fig" src="figures_own/fig-${r.i}.svg" alt="figure for #${r.i}">` +
    `<h1>#${r.i}</h1>` + meta + explore + body;
  const ob = $('openExplore');
  if (ob) ob.addEventListener('click', () => window.Explore.open(r.i));
  // A picture is the quickest way into a combo, so make it the way in. It opens THAT combo on THAT shape --
  // not a fresh solve of the same combo, which could land on a different member of the family and show you
  // a different tile from the one you pointed at.
  card.querySelectorAll('[data-open]').forEach(el => el.addEventListener('click', () => {
    if (el.dataset.open === 'iso') {
      const eg = window.ISO_EXAMPLES && window.ISO_EXAMPLES[r.i];
      if (eg) window.Explore.openShape({ id: r.i, m: eg.m, si: eg.si, or: eg.or, off: eg.off }, eg);
    } else {
      const c = lastDrawn[+el.dataset.i];
      if (c) window.Explore.openShape({ id: r.i, m: c.m, si: c.si, or: c.or, off: c.off }, c.shape);
    }
  }));

}

// ---------- selection: the single entry point ----------
// syncFilter=true also narrows sig/orb to the selected type's own signature/orbifold (used for
// id-box / prev / next / deep-link, which don't originate from the filtered list). A grid click
// or a "match" dropdown pick leaves the filter exactly as the user set it -- the list they picked
// from is already consistent with it.
function selectType(id, { syncFilter = false } = {}) {
  const r = byId[id];
  if (!r) { showIdError(id); return; }
  hideIdError();
  state.selectedId = id;
  if (syncFilter) {
    state.sig = sigOf(r);
    $('sigSel').value = state.sig;
    buildOrbList();
    state.orb = r.o;
    $('orbSel').value = r.o;
  }
  refreshFilterViews();
  renderCard(r);
  $('idBox').value = id;
  if (history.replaceState) history.replaceState(null, '', '#' + id);
  else location.hash = '#' + id;
}

function showIdError(idStr) {
  const el = $('idErr');
  el.textContent = `#${idStr} is not a Tegula type id`;
  el.style.display = 'inline';
}
function hideIdError() { $('idErr').style.display = 'none'; }

function step(delta) {
  const n = sortedIds.length;
  let i = state.selectedId == null ? -1 : sortedIds.indexOf(state.selectedId);
  i = i === -1 ? (delta > 0 ? -1 : 0) : i;
  const next = sortedIds[(i + delta + n) % n];
  selectType(next, { syncFilter: true });
}

function pickId() {
  const raw = $('idBox').value.trim();
  if (!raw) { hideIdError(); return; }
  const id = +raw;
  if (!Number.isInteger(id) || !byId[id]) { showIdError(raw); return; }
  selectType(id, { syncFilter: true });
}

// ---------- menubar: click to open, Escape / click-outside to close ----------
function wireMenubar() {
  const topButtons = document.querySelectorAll('#menubar > ul > li > button');
  topButtons.forEach(btn => {
    btn.addEventListener('click', e => {
      e.stopPropagation();
      const li = btn.parentElement;
      const wasOpen = li.classList.contains('open');
      closeMenus();
      if (!wasOpen) li.classList.add('open');
    });
  });
  document.addEventListener('click', closeMenus);
  document.addEventListener('keydown', e => { if (e.key === 'Escape') closeMenus(); });
}
function closeMenus() {
  document.querySelectorAll('#menubar li.open').forEach(li => li.classList.remove('open'));
}

// ---------- wiring ----------
function init() {
  buildSigList();
  buildOrbList();
  refreshFilterViews();
  wireMenubar();

  $('sigSel').addEventListener('change', () => { state.sig = $('sigSel').value; buildOrbList(); refreshFilterViews(); });
  $('orbSel').addEventListener('change', () => { state.orb = $('orbSel').value; refreshFilterViews(); });
  $('typeSel').addEventListener('change', () => selectType(+$('typeSel').value));
  // Sort only reorders the list and grid. It must NOT select anything -- same rule as the filters
  // (program6 fused "narrow the list" with "pick a type" and double-selected).
  $('sortSel').addEventListener('change', () => { state.sort = $('sortSel').value; refreshFilterViews(); });

  // ---- modes. A null entry is built; the rest show what they will do. ----
  const STUBS = {
    gallery: null,                    // built -- see js/gallery.js
    deep: null,                       // built -- see js/deep.js
    copy: null,                       // built -- see js/copy.js
    explore: null,
  };
  function setMode(mode) {
    state.mode = mode;
    // Explore's workspace and Deep search are full-page sections of their own; leaving either on screen while
    // another mode is selected is how two modes end up visible at once.
    if (mode !== 'explore' && window.Explore) window.Explore.close();
    $('deep').hidden = mode !== 'deep';
    $('gallery').hidden = mode !== 'gallery';
    $('copy').hidden = mode !== 'copy';
    [...document.querySelectorAll('#modebar button')].forEach(b => {
      const on = b.dataset.mode === mode;
      b.classList.toggle('on', on); b.setAttribute('aria-selected', on ? 'true' : 'false');
    });
    const stub = STUBS[mode];
    $('stub').hidden = !stub;
    // The filter/sort bar narrows the type LIST. The gallery is a page of tiles, not of types, so the bar
    // would sit there filtering something the mode does not show.
    $('selectors').hidden = !!stub || mode === 'gallery' || mode === 'copy';
    const main = document.querySelector('main') || document.getElementById('layout');
    if (main) main.hidden = !!stub || mode === 'deep' || mode === 'gallery' || mode === 'copy';
    if (mode === 'deep' && window.Deep) window.Deep.init(state.selectedId);
    if (mode === 'gallery' && window.Gallery) window.Gallery.init();
    if (mode === 'copy' && window.CopyTiling) window.CopyTiling.init(state.selectedId);
    if (!stub) { $('stubTitle').textContent = ''; $('stubWhat').textContent = ''; $('stubPlan').innerHTML = ''; }
    if (stub) {
      $('stubTitle').textContent = stub.title;
      $('stubWhat').textContent = stub.what;
      $('stubPlan').innerHTML = stub.plan.map(x => `<li>${x}</li>`).join('');
    }
  }
  [...document.querySelectorAll('#modebar button')].forEach(b =>
    b.addEventListener('click', () => setMode(b.dataset.mode)));
  setMode('explore');
  // Explore needs two things the picker owns: the type row, and the store's view of a type. Lent as
  // functions rather than copied, so there is still one of each.
  window.byIdForExplore = id => byId[id];
  window.showMode = setMode;                       // Deep search sends you to Explore when you click a result
  $('exBack').addEventListener('click', () => window.Explore.close());

  $('idBox').addEventListener('keydown', e => { if (e.key === 'Enter') pickId(); });
  $('idBox').addEventListener('blur', pickId);
  $('prevBtn').addEventListener('click', () => step(-1));
  $('nextBtn').addEventListener('click', () => step(1));

  document.addEventListener('keydown', e => {
    const tag = (e.target.tagName || '').toLowerCase();
    if (tag === 'input' || tag === 'select' || tag === 'textarea') return;
    if (document.querySelector('dialog[open]')) return;
    if (e.key === 'ArrowRight') { e.preventDefault(); step(1); }
    else if (e.key === 'ArrowLeft') { e.preventDefault(); step(-1); }
  });

  $('copyLink').addEventListener('click', async () => {
    closeMenus();
    if (state.selectedId == null) return;
    const url = location.href.split('#')[0] + '#' + state.selectedId;
    try { await navigator.clipboard.writeText(url); }
    catch (e) { window.prompt('Copy this link:', url); }
  });
  $('showAbout').addEventListener('click', () => { closeMenus(); $('aboutDlg').showModal(); });
  $('showKeys').addEventListener('click', () => { closeMenus(); $('keysDlg').showModal(); });

  window.addEventListener('hashchange', fromHash);
  fromHash();
  // A native <select> shows its first option as chosen even with no 'change' fired, which would
  // otherwise leave the "match" dropdown looking selected while the card still said "pick a
  // type". Give the page a real, consistent starting selection instead (unless a deep link
  // already picked one).
  if (state.selectedId == null) selectType(sortedIds[0]);
}

function fromHash() {
  const raw = location.hash.replace('#', '').trim();
  if (!raw) return;
  if (raw === 'gallery-pdf') { if (window.showMode) window.showMode('gallery'); return; }   // the printable gallery (js/gallery.js)
  // a link to one combo (File > "Copy link to this combo"): straight into Explore on it (js/explore.js openLink)
  if (/^combo=/.test(raw)) {
    const params = new URLSearchParams(raw);
    const id = +String(params.get('combo') || '').split('/')[0];
    if (Number.isInteger(id) && byId[id]) { state.selectedId = id; if (window.Explore && window.Explore.openLink) window.Explore.openLink(params); }
    return;
  }
  const id = +raw;
  if (Number.isInteger(id) && byId[id]) selectType(id, { syncFilter: true });
}

init();
