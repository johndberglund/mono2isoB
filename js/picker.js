// ---------- the filtered list driving both the "match" dropdown and the grid ----------
// ---------- sort orders (John, 2026-09-30) -----------------------------------------------------
//   tegula   by Tegula id (what slice 1 did, and still the default)
//   paper    the order the figures appear in Delgado, Huson & Zamorzaeva -- read off the figure
//            filename, which is p<page>_<position>.png. All 1270 parse, pages 53-116, and no two
//            types share a (page, position), so it is a genuine total order and needs no new data.
//   verdict  red X, then unknown, then yellow tick, then green tick, each group by id. That is
//            John's stated order: what is settled impossible first, what is unknown next, and the
//            types we know most about last.
const paperKey = r => {
  return r.pp ? r.pp[0] * 1000 + r.pp[1] : Infinity;   // [page, position] in the paper: page dominates, position breaks ties
};
// rank must agree with markOf: green needs an anisohedral example, which arrives with combos.js
const verdictRank = r => {
  if (r.v === 'X') return 0;
  if (r.v === 'U') return 1;
  return hasAniso(r.i) ? 3 : 2;                     // possible: yellow (2) before green (3)
};
const SORTS = {
  tegula:  (a, b) => a.i - b.i,
  paper:   (a, b) => paperKey(a) - paperKey(b) || a.i - b.i,
  verdict: (a, b) => verdictRank(a) - verdictRank(b) || a.i - b.i,
};

function filtered() {
  const cmp = SORTS[state.sort] || SORTS.tegula;
  return TYPES.filter(r => (!state.sig || sigOf(r) === state.sig) && (!state.orb || r.o === state.orb))
    .sort(cmp);
}

