// ---------- signature list (static: 147 k_q n_r signatures over all 1270 ids) ----------
// Rows are already canonical (smaller side count first, tie-broken by index -- see
// program7/app_tools/gen_types.js), so this only decides browsing order, not grouping. Sorted by side count
// first (k, then n), THEN by index (q, then r) -- not k,q,n,r -- so it groups the way the paper's
// own table does: all "3_1 ..." entries together, then all "3_2 ..." entries, etc.
function buildSigList() {
  const counts = new Map();
  TYPES.forEach(r => { const s = sigOf(r); counts.set(s, (counts.get(s) || 0) + 1); });
  const sigs = [...counts.keys()].sort((a, b) => {
    const [ak, aq, an, ar] = a.split(/[_ ]/).map(Number);
    const [bk, bq, bn, br] = b.split(/[_ ]/).map(Number);
    return ak - bk || an - bn || aq - bq || ar - br;
  });
  const sel = $('sigSel');
  sel.innerHTML = `<option value="">any (${TYPES.length})</option>`;
  sigs.forEach(s => {
    const o = document.createElement('option');
    o.value = s; o.textContent = `${s}  (${counts.get(s)})`;
    sel.appendChild(o);
  });
}

